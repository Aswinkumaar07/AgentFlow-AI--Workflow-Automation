import React, { useState, useEffect, useCallback } from 'react';
import { oauthApi } from '../../api/oauth';
import { saveWorkflowOAuthSnapshot } from '../../utils/oauthWorkflowPersistence';
import {
  RefreshCw, AlertTriangle, X, CheckCircle2, Lock, ArrowRight, KeyRound,
} from 'lucide-react';

interface OAuthConnectModalProps {
  isOpen: boolean;
  provider: string;
  connectUrl?: string;
  scopes?: string[];
  onConnected?: (accountLabel: string) => void;
  onClose: () => void;
}

export const OAuthConnectModal: React.FC<OAuthConnectModalProps> = ({
  isOpen,
  provider,
  onClose,
}) => {
  const [step, setStep] = useState<'idle' | 'waiting' | 'connected' | 'error'>('idle');
  const [errorMsg, setErrorMsg] = useState('');

  const handleConnect = useCallback(async () => {
    setStep('waiting');
    setErrorMsg('');

    try {
      // Save workflow DAG snapshot before full-page OAuth redirect
      saveWorkflowOAuthSnapshot();

      // Backend-driven OAuth login redirect
      await oauthApi.connectAccount(provider);
    } catch (err: any) {
      setStep('error');
      setErrorMsg(err.message || `Failed to initiate OAuth flow for ${provider}.`);
    }
  }, [provider]);

  // Cleanup on close
  useEffect(() => {
    if (!isOpen) {
      setStep('idle');
      setErrorMsg('');
    }
  }, [isOpen]);

  if (!isOpen) return null;

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-black/60 backdrop-blur-sm animate-in fade-in duration-200">
      <div className="w-full max-w-md rounded-2xl border border-border bg-card p-6 shadow-2xl space-y-5 relative">
        <button
          onClick={onClose}
          className="absolute top-4 right-4 p-1 rounded-lg text-muted-foreground hover:text-foreground hover:bg-muted transition"
        >
          <X className="h-4 w-4" />
        </button>

        {/* ── Header ── */}
        <div className="flex items-center gap-3">
          <div className="h-10 w-10 rounded-xl bg-primary/10 text-primary flex items-center justify-center font-bold text-base">
            {provider[0]?.toUpperCase()}
          </div>
          <div>
            <h3 className="font-bold text-base tracking-tight">Connect {provider} Account</h3>
            <p className="text-xs text-muted-foreground">Single Source OAuth · Backend Direct</p>
          </div>
        </div>

        {/* ── Step: Idle / Pre-Flight ── */}
        {step === 'idle' && (
          <div className="space-y-4">
            <div className="p-3.5 rounded-xl border border-border bg-muted/30 text-xs space-y-2">
              <div className="flex items-center gap-2 text-foreground font-semibold">
                <Lock className="h-4 w-4 text-emerald-500 shrink-0" />
                <span>Backend-Driven OAuth Authentication</span>
              </div>
              <p className="text-muted-foreground leading-relaxed">
                Clicking connect will redirect to the official {provider} login URL generated by the backend API.
              </p>
            </div>

            <div className="flex justify-end gap-2 pt-2">
              <button
                onClick={onClose}
                className="px-4 py-2 rounded-xl border border-border text-xs font-semibold text-muted-foreground hover:bg-muted transition"
              >
                Cancel
              </button>
              <button
                onClick={handleConnect}
                className="px-4 py-2 rounded-xl bg-primary text-primary-foreground text-xs font-semibold hover:bg-primary/90 transition flex items-center gap-1.5 shadow-sm"
              >
                <KeyRound className="h-3.5 w-3.5" />
                Authenticate via Backend
                <ArrowRight className="h-3.5 w-3.5 ml-0.5" />
              </button>
            </div>
          </div>
        )}

        {/* ── Step: Waiting / Redirecting ── */}
        {step === 'waiting' && (
          <div className="py-6 text-center space-y-3">
            <div className="h-12 w-12 rounded-full bg-primary/10 text-primary flex items-center justify-center mx-auto animate-spin">
              <RefreshCw className="h-6 w-6" />
            </div>
            <div>
              <p className="font-bold text-sm">Redirecting to Backend OAuth…</p>
              <p className="text-xs text-muted-foreground mt-0.5">Contacting /api/v1/oauth/{provider.toLowerCase()}/login</p>
            </div>
          </div>
        )}

        {/* ── Step: Connected ── */}
        {step === 'connected' && (
          <div className="py-6 text-center space-y-3">
            <div className="h-12 w-12 rounded-full bg-emerald-500/10 text-emerald-500 flex items-center justify-center mx-auto">
              <CheckCircle2 className="h-6 w-6" />
            </div>
            <div>
              <p className="font-bold text-sm text-emerald-500">Successfully Connected!</p>
            </div>
          </div>
        )}

        {/* ── Step: Error ── */}
        {step === 'error' && (
          <div className="space-y-4">
            <div className="p-3.5 rounded-xl border border-rose-500/20 bg-rose-500/10 text-rose-500 text-xs space-y-1">
              <div className="flex items-center gap-1.5 font-bold">
                <AlertTriangle className="h-4 w-4 shrink-0" />
                <span>Connection Error</span>
              </div>
              <p>{errorMsg || 'Failed to complete OAuth authentication.'}</p>
            </div>

            <div className="flex justify-end gap-2">
              <button
                onClick={onClose}
                className="px-4 py-2 rounded-xl border border-border text-xs font-semibold text-muted-foreground hover:bg-muted transition"
              >
                Close
              </button>
              <button
                onClick={handleConnect}
                className="px-4 py-2 rounded-xl bg-primary text-primary-foreground text-xs font-semibold hover:bg-primary/90 transition"
              >
                Retry
              </button>
            </div>
          </div>
        )}
      </div>
    </div>
  );
};
