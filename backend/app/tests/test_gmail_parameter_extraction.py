def test_planner_workflow_json_structure():
    prompt = "Send email to user@example.com Subject: AgentFlow Test 1 Body: Hello,\n\nThis email was generated automatically.\n\nRegards,\nAgentFlow"
    plan = intelligent_planner_v4.plan(prompt)

    gmail_nodes = [n for n in plan.workflow_graph["nodes"] if n.get("provider") in ["gmail", "google_gmail"]]
    assert len(gmail_nodes) > 0

    node = gmail_nodes[0]
    params = node["parameters"]

    assert params["to"] == "user@example.com"
    assert params["subject"] == "AgentFlow Test 1"
    assert params["body"] == "Hello,\n\nThis email was generated automatically.\n\nRegards,\nAgentFlow"

    assert "\r" not in params["to"] and "\n" not in params["to"]
    assert "\r" not in params["subject"] and "\n" not in params["subject"]
    assert "To:" not in params["to"]
    assert "Subject:" not in params["subject"]
    assert "Body:" not in params["body"]


def test_sprint_auth13_end_to_end_verification():
    prompt = """Send an email to john@example.com

Subject:
Sprint AUTH-13 Verification

Body:
Hello John,

This email is generated by AgentFlow AI.

Regards,
Aswin"""

    plan = intelligent_planner_v4.plan(prompt)
    gmail_nodes = [n for n in plan.workflow_graph["nodes"] if n.get("provider") in ["gmail", "google_gmail"]]
    assert len(gmail_nodes) > 0

    params = gmail_nodes[0]["parameters"]
    assert params["to"] == "john@example.com"
    assert params["subject"] == "Sprint AUTH-13 Verification"
    assert params["body"] == "Hello John,\n\nThis email is generated by AgentFlow AI.\n\nRegards,\nAswin"

    assert "Regarding:" not in params["body"]
    assert "Subject:" not in params["subject"]
    assert "Body:" not in params["body"]
    assert "\r" not in params["to"] and "\n" not in params["to"]
    assert "\r" not in params["subject"] and "\n" not in params["subject"]

