import pytest
from app.agents.planner.gmail_parameter_extractor import extract_gmail_parameters
from app.agents.planner.planner_v4 import intelligent_planner_v4


def test_explicit_subject_and_body():
    prompt = "Send email to user@example.com Subject: AgentFlow Test 1 Body: Hello,\n\nThis email was generated automatically.\n\nRegards,\nAgentFlow"
    result = extract_gmail_parameters(prompt)

    assert result["to"] == "user@example.com"
    assert result["subject"] == "AgentFlow Test 1"
    assert result["body"] == "Hello,\n\nThis email was generated automatically.\n\nRegards,\nAgentFlow"
    assert "\r" not in result["to"] and "\n" not in result["to"]
    assert "\r" not in result["subject"] and "\n" not in result["subject"]


def test_prompt_without_subject():
    prompt = "Send email to alex@company.org Body: Please review the attached Q3 report."
    result = extract_gmail_parameters(prompt)

    assert result["to"] == "alex@company.org"
    assert result["subject"] != ""
    assert len(result["subject"].split()) >= 3 and len(result["subject"].split()) <= 8
    assert result["body"] == "Please review the attached Q3 report."
    assert "\r" not in result["subject"] and "\n" not in result["subject"]


def test_prompt_without_body():
    prompt = "Send email to dev@team.io Subject: Critical Security Advisory"
    result = extract_gmail_parameters(prompt)

    assert result["to"] == "dev@team.io"
    assert result["subject"] == "Critical Security Advisory"
    assert result["body"] != ""
    assert "AgentFlow" in result["body"] or "automatically" in result["body"]
